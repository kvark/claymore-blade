const fn unit(
    id: &'static str,
    name: &'static str,
    title: &'static str,
    rank: i32,
    side: Side,
    portrait: &'static str,
    sprite: &'static str,
    stats: Stats,
    skills: &'static [&'static str],
    trans: i32,
    color: [f32; 3],
    hp: i32,
) -> UnitTemplate {
    UnitTemplate {
        id,
        name,
        title,
        rank,
        side,
        portrait,
        sprite,
        stats,
        skills,
        trans,
        footprint: &[Axial { q: 0, r: 0 }],
        core_index: 0,
        parts: &[],
        body_hp: hp,
        color,
    }
}

