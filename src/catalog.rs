//! Series roster, skills, island, hunts.

use crate::combat::{Attr, ShapeKind, Side, SkillDef, Stats, UnitTemplate};
use crate::hex::Axial;

pub fn skill(id: &str) -> Option<&'static SkillDef> {
    SKILLS.iter().find(|s| s.id == id)
}

pub fn warrior(id: &str) -> Option<&'static UnitTemplate> {
    WARRIORS.iter().find(|u| u.id == id)
}

pub fn enemy(id: &str) -> Option<&'static UnitTemplate> {
    ENEMIES.iter().find(|u| u.id == id)
}

pub fn location(id: &str) -> Option<&'static LocationDef> {
    LOCATIONS.iter().find(|l| l.id == id)
}

pub fn encounter(id: &str) -> Option<&'static EncounterDef> {
    ENCOUNTERS.iter().find(|e| e.id == id)
}

pub fn derived(stats: &Stats) -> Derived {
    Derived {
        hit: stats.a + stats.c,
        dodge: stats.a + stats.p + stats.w,
        r#move: (stats.a / 3).max(2),
        yoki: 8 + stats.w * 4,
        strikes: (stats.a / 4).max(1),
    }
}

#[derive(Clone, Copy, Debug)]
pub struct Derived {
    pub hit: i32,
    pub dodge: i32,
    pub r#move: i32,
    pub yoki: i32,
    pub strikes: i32,
}

#[derive(Clone, Copy, Debug)]
pub struct LocationDef {
    pub id: &'static str,
    pub name: &'static str,
    pub region: &'static str,
    pub blurb: &'static str,
    pub x: f32,
    pub y: f32,
    pub kind: &'static str,
    pub encounter: Option<&'static str>,
    pub deadline: i32,
    pub art: &'static str,
}

#[derive(Clone, Copy, Debug)]
pub struct EnemySpawn {
    pub template: &'static str,
    pub origin: Axial,
    pub facing: i32,
}

#[derive(Clone, Copy, Debug)]
pub struct EncounterDef {
    pub id: &'static str,
    pub title: &'static str,
    pub briefing: &'static str,
    pub art: &'static str,
    pub cols: i32,
    pub rows: i32,
    pub enemies: &'static [EnemySpawn],
    pub player_origins: &'static [Axial],
    pub karma: i32,
    pub rank: i32,
    pub recruit: &'static [&'static str],
    pub raki: bool,
    pub flag: &'static str,
}

