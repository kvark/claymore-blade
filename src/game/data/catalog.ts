export function derived(stats: UnitTemplate["stats"]) {
  return {
    hit: stats.A + stats.C,
    dodge: stats.A + stats.P + stats.W,
    detect: stats.P,
    move: Math.max(2, Math.round(stats.A / 3)),
    transMax: stats.C + stats.W,
    health: 28 + stats.S * 6,
    yoki: 8 + stats.W * 4,
    damage: stats.S,
    strikes: Math.max(1, Math.round(stats.A / 4)),
  };
}

